START WITH 101
INCREMENT BY 1
MAXVALUE 200
CACHE 3
CYCLE;

CREATE SEQUENCE dp
START WITH 1
INCREMENT BY 1
MAXVALUE 10
CACHE 3
CYCLE;

CREATE SEQUENCE ap
START WITH 30
